const allSeoPages = db.prepare("SELECT * FROM seo_pages").all();
let updatedCount = 0;

const updateStmt = db.prepare(`
  UPDATE seo_pages
  SET content = :content,
      excerpt = :excerpt,
      status = 'published',
      is_active = 1,
      updated_at = :now
  WHERE id = :id
`);

for (const p of allSeoPages) {
  const content = p.content || "";
  const excerpt = p.excerpt || "";
  const title = p.title || "";
  const kw = (p.target_keyword || title || p.slug || "").toLowerCase();

  // Check if page has draft / placeholder text
  const isPlaceholder = content.includes("مسودة") ||
                        excerpt.includes("مسودة") ||
                        content.includes("نطاق") ||
                        excerpt.includes("نطاق") ||
                        content.includes("فريق الإدارة") ||
                        content.includes("مراجعة داخلية") ||
                        content.includes("محفوظة كمسودة") ||
                        p.status === "draft" ||
                        content.length < 150;

  if (isPlaceholder) {
    let genResult;
    const city = title.includes("بالخرج") ? "بالخرج" : "بالرياض";

    if (kw.includes("مكيف") || kw.includes("تكييف") || kw.includes("سبلت") || p.slug.includes("air-conditioner") || p.slug.includes("مكيفات")) {
      genResult = pageContentGenerators.ac(title, kw, city);
    } else if (kw.includes("نقل") || kw.includes("عفش") || kw.includes("اثاث") || kw.includes("أثاث") || kw.includes("دينا") || kw.includes("ونيت")) {
      genResult = pageContentGenerators.move(title, kw, city);
    } else if (kw.includes("عزل") || kw.includes("تسرب") || kw.includes("تسربات") || kw.includes("اسطح") || kw.includes("أسطح")) {
      genResult = pageContentGenerators.insulation(title, kw, city);
    } else if (kw.includes("مجاري") || kw.includes("تسليك") || kw.includes("صرف")) {
      genResult = pageContentGenerators.sewage(title, kw, city);
    } else if (kw.includes("تطبيق") || kw.includes("برنامج") || kw.includes("منصة")) {
      genResult = pageContentGenerators.app(title, kw, city);
    } else {
      genResult = pageContentGenerators.general(title, kw, city);
    }

    updateStmt.run({
      id: p.id,
      content: genResult.content.trim(),
      excerpt: genResult.excerpt.trim(),
      now: new Date().toISOString()
    });

    updatedCount++;
    console.log(`✅ تم تحديث ونشر الصفحة [ID: ${p.id}]: "${p.title}" بنص احترافي كامل.`);
  }
}

console.log(`\n🎉 تم تحديث ${updatedCount} صفحة بمحتوى تسويقي حقيقي وموثوق!`);
